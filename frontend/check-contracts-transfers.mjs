import assert from 'node:assert/strict';
import { createServer } from 'vite';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';

let permissions = [];
globalThis.window = { location: { hostname: '127.0.0.1', pathname: '/pages/payroll.html' } };
globalThis.localStorage = { getItem: (key) => key === 'user' ? JSON.stringify({ permissions }) : key === 'access_token' ? 'test-only' : null };
const server = await createServer({ server: { middlewareMode: true } });
try {
  const { default: ContractEditor } = await server.ssrLoadModule('/modules/module-1/components/ContractEditor.jsx');
  const { ContractList } = await server.ssrLoadModule('/modules/module-1/components/EmployeeContracts.jsx');
  const { default: Page } = await server.ssrLoadModule('/modules/module-4/pages/PayrollPage.jsx');
  const { TransferList, default: TransferOrders } = await server.ssrLoadModule('/modules/module-4/components/TransferOrders.jsx');
  const { TransferInformation } = await server.ssrLoadModule('/modules/module-4/components/TransferDetail.jsx');
  const { default: TransferEditor } = await server.ssrLoadModule('/modules/module-4/components/TransferEditor.jsx');
  const { default: TransferDecision } = await server.ssrLoadModule('/modules/module-4/components/TransferDecision.jsx');
  const { eligiblePayrolls, reconcilablePayrolls, transferActions } = await server.ssrLoadModule('/modules/module-4/lib/transfers.js');
  const render = (Component, props = {}) => renderToStaticMarkup(React.createElement(Component, props));
  const mutation = { errors: {}, message: '', saving: false, submit() {} };
  const contract = { id: 1, date_debut: '2026-01-01', date_fin: null, salaire_base: '300000', heures_journalieres: '8', type: [1], types_libelles: ['CDI'], statut: 'EN_COURS' };
  const readonly = render(ContractList, { contracts: [contract], onEdit() {}, onDelete() {} });
  assert(readonly.includes('CDI'));
  assert(readonly.includes('8 h/jour'));
  assert(!readonly.includes('>Modifier<'));
  permissions = ['contrat.update', 'contrat.delete'];
  const managed = render(ContractList, { contracts: [contract], onEdit() {}, onDelete() {} });
  assert(managed.includes('>Modifier<'));
  assert(managed.includes('>Supprimer<'));
  const contractForm = render(ContractEditor, { contract: null, employeeId: 1, types: [{ id: 1, type: 'CDI' }], canChooseTypes: true, mutation, onClose() {}, onSaved() {} });
  for (const label of ['Salaire mensuel de base', 'Date de début', 'Heures de travail par jour', 'Types de contrat']) assert(contractForm.includes(label));
  assert(contractForm.includes('multiple=""'));
  assert(contractForm.includes('max="24"'));
  const payroll = { id: 1, employe: 1, employe_nom: 'Test', employe_prenom: 'Alice', periode: '2026-10', salaire_net: '250000', devise: 'XOF', statut: 'VALIDEE' };
  const order = { id: 8, employe: 1, employe_nom: 'Test', employe_prenom: 'Alice', periode: '2026-10', statut: 'GENERE', date_generation: '2026-10-23T12:00:00Z' };
  assert.equal(eligiblePayrolls([payroll, { ...payroll, id: 2, statut: 'BROUILLON' }], []).length, 1);
  assert.equal(eligiblePayrolls([payroll], [order]).length, 0);
  assert.equal(eligiblePayrolls([payroll], [order], order).length, 1);
  assert.equal(eligiblePayrolls([payroll], [{ ...order, statut: 'REJETE' }]).length, 1);
  const creator = { create: true };
  assert.deepEqual(transferActions(order, creator, [payroll]), []);
  const updater = { update: true };
  assert.deepEqual(transferActions(order, updater, [payroll]), ['traiter', 'rejeter', 'annuler']);
  const treated = { ...order, statut: 'TRAITE', date_traitement: '2026-10-23T12:05:00Z' };
  const manager = { update: true, delete: true, payrollRead: true, payrollUpdate: true };
  assert.deepEqual(transferActions(treated, manager, [payroll]), ['reconcile']);
  assert.equal(reconcilablePayrolls(treated, [{ ...payroll, statut: 'PAYE', ordre_virement: 8 }]).length, 0);
  assert.deepEqual(transferActions({ ...order, statut: 'ANNULE' }, manager, [payroll]), []);
  const readOrders = render(TransferList, { orders: [order], payrolls: [payroll], permissions: {}, onDetail() {}, onAction() {} });
  assert(readOrders.includes('Alice Test'));
  assert(readOrders.includes('Voir le détail'));
  assert(!readOrders.includes('>Traiter<'));
  const generatedOrder = render(TransferList, { orders: [order], payrolls: [payroll], permissions: manager, onDetail() {}, onAction() {} });
  assert(generatedOrder.includes('>Modifier l’ordre<'));
  assert(generatedOrder.includes('>Supprimer l’ordre<'));
  const closedOrder = render(TransferList, { orders: [treated], payrolls: [payroll], permissions: manager, onDetail() {}, onAction() {} });
  assert(!closedOrder.includes('>Modifier l’ordre<'));
  assert(!closedOrder.includes('>Supprimer l’ordre<'));
  assert(closedOrder.includes('Ordre traité : modification et suppression indisponibles'));
  const orderManager = render(TransferOrders, { orders: [], payrolls: [payroll], loading: false, error: '', payrollError: '', permissions: { ...manager, create: true }, onChanged() {} });
  assert(orderManager.includes('>Créer un ordre de virement<'));
  assert(!render(TransferInformation, { order }).includes('<button'));
  assert(render(TransferEditor, { order: null, payrolls: [payroll], orders: [], mutation, onClose() {}, onSaved() {} }).includes('Alice Test'));
  const rejection = render(TransferDecision, { action: 'rejeter', order, payrolls: [payroll], mutation, onClose() {}, onSaved() {} });
  assert(rejection.includes('Motif de la décision'));
  assert(rejection.includes('required=""'));
  permissions = ['ordre_virement.read'];
  const onlyOrdersPage = render(Page);
  assert(onlyOrdersPage.includes('Ordres de virement'));
  assert(onlyOrdersPage.includes('payroll.html'));
  assert(!onlyOrdersPage.includes('>Règles de paie<'));
  assert(!onlyOrdersPage.includes('>Nouvelle paie<'));
  console.log('Contrats et ordres : formulaires, permissions, états, éligibilité, rapprochement et détails en lecture seule OK');
} finally {
  await server.close();
}
