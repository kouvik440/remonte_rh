import assert from 'node:assert/strict';
import { createServer } from 'vite';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';

let permissions = [];
globalThis.window = { location: { hostname: '127.0.0.1' } };
globalThis.localStorage = { getItem: (key) => key === 'access_token' ? 'test-only' : key === 'user' ? JSON.stringify({ permissions }) : null };
const server = await createServer({ server: { middlewareMode: true, hmr: false }, optimizeDeps: { noDiscovery: true } });
try {
  const { default: Page } = await server.ssrLoadModule('/modules/module-7/pages/TimesheetsPage.jsx');
  const { default: Lines } = await server.ssrLoadModule('/modules/module-7/components/TimesheetLines.jsx');
  const { default: Editor } = await server.ssrLoadModule('/modules/module-7/components/TimesheetEditor.jsx');
  const { default: NameForm } = await server.ssrLoadModule('/modules/module-7/components/ProjectNameForm.jsx');
  const { default: ProjectTable } = await server.ssrLoadModule('/modules/module-7/components/ProjectTable.jsx');
  const { default: ProjectTaskTable } = await server.ssrLoadModule('/modules/module-7/components/ProjectTaskTable.jsx');
  const { CostReconciliation } = await server.ssrLoadModule('/modules/module-7/components/TimesheetCosts.jsx');
  const { validateSheet, sheetPayload, parseDate, weekEnd, readableError, currency } = await server.ssrLoadModule('/modules/module-7/lib/timesheets.js');
  const render = (Component, props = {}) => renderToStaticMarkup(React.createElement(Component, props));
  const employeePage = render(Page);
  assert(employeePage.includes('Mes feuilles'));
  assert(employeePage.includes('Feuilles de temps'));
  assert(!employeePage.includes('À valider'));
  assert(!employeePage.includes('Rapprochement des coûts'));
  assert(!employeePage.includes('Projets et affectations'));
  permissions = ['feuille_temps.decide', 'paie.read', 'projet.read'];
  const managerPage = render(Page);
  for (const text of ['À valider', 'Rapprochement des coûts', 'Projets et affectations']) assert(managerPage.includes(text));
  const projects = [{ id: 1, code: 'P-1', nom: 'Projet', taches: [{ id: 2, nom: 'Analyse' }] }];
  const line = { key: 'test', date: '2026-10-20', project: '1', task: '2', unit: 'jours', quantity: '0,5', comment: ' Analyse ' };
  assert.deepEqual(validateSheet('2026-10-19', [line], projects), {});
  assert(validateSheet('2026-10-20', [line], projects).week);
  assert(validateSheet('2026-10-19', [{ ...line, date: '2026-10-26' }], projects)['line-0-date']);
  assert(validateSheet('2026-10-19', [{ ...line, quantity: '1.01' }], projects)['line-0-quantity']);
  assert(validateSheet('2026-10-19', [{ ...line, unit: 'heures', quantity: '24.01' }], projects)['line-0-quantity']);
  assert(validateSheet('2026-10-19', [line], [])['line-0-project']);
  assert.deepEqual(sheetPayload('2026-10-19', [line]).lignes[0], { date_travail: '2026-10-20', projet: 1, tache: 2, jours: '0.5', commentaire: 'Analyse' });
  assert.equal(weekEnd('2026-10-19'), '2026-10-25');
  assert.equal(parseDate('2026-02-30'), null);
  assert(parseDate('0001-01-01'));
  assert.equal(readableError({ lignes: [{ heures: ['Trop d’heures.'] }] }), 'Lignes : Ligne 1 : Heures : Trop d’heures.');
  const sheet = { id: 1, semaine_debut: '2026-10-19', statut: 'BROUILLON', total_heures: '3.00', jours_saisis: 1, motif_refus: 'Préciser la tâche', lignes: [{ id: 10, date_travail: '2026-10-20', projet: 1, projet_code: 'P-1', projet_nom: 'Projet', tache: 2, tache_nom: 'Analyse', heures: '3.00', commentaire: 'Travail' }] };
  const detail = render(Lines, { sheet });
  for (const text of ['3.00 h', 'Préciser la tâche', 'tabindex="0"', 'scope="row"', 'Analyse']) assert(detail.includes(text));
  const editor = render(Editor, { sheet: { ...sheet, statut: 'VALIDEE' }, projects: { report: projects, loading: false, error: '' }, mutation: { busy: false, error: '' } });
  assert(editor.includes('remettra la feuille en brouillon'));
  assert(editor.includes('Jours / fraction de jour'));
  assert(editor.includes('Actualiser les projets et tâches'));
  const projectForm = render(NameForm, { title: 'Nouveau projet', path: '/api/projets/', mutation: { busy: false, error: '' } });
  assert(!projectForm.includes('>Code<'));
  assert(projectForm.includes('>Nom<'));
  const projectTable = render(ProjectTable, { projects: [{ id: 1, nom: 'Portail RH', actif: true }], selected: '', onSelect() {} });
  assert(projectTable.includes('<table'));
  assert(projectTable.includes('Gérer les tâches de Portail RH'));
  const taskTable = render(ProjectTaskTable, { tasks: [{ id: 1, nom: 'Analyse', actif: true, employes: [2] }, { id: 2, nom: 'Validation', actif: true, employes: [] }],
    assignments: [{ employe: 2, employe_prenom: 'Aminata', employe_nom: 'Test' }], canAssign: true, canDelete: false });
  assert(taskTable.includes('Aminata Test'));
  assert(taskTable.includes('À affecter'));
  assert(taskTable.includes('scope="row"'));
  const totals = { heures_validees: '3.00', heures_sans_tgm: '0.00', cout_calculable: '6000.00', cout_estime: '6000.00', cout_complet: true };
  const report = { date_debut: '2026-10-01', date_fin: '2026-10-31', totaux: totals, rapprochement: [{ ...totals, projet_id: 1, projet_code: 'P-1', projet_nom: 'Projet', employe_id: 1, employe_prenom: 'Test', employe_nom: 'Exemple', periode: '2026-10', taux_horaire_charge: '2000.00' }] };
  const costs = render(CostReconciliation, { report });
  assert(costs.includes(currency('2000')));
  assert(costs.includes(currency('6000')));
  assert(render(CostReconciliation, { report: { ...report, totaux: { ...totals, heures_sans_tgm: '1.00', cout_complet: false } } }).includes('Coût incomplet'));
  console.log('Module 7 : accès employé/manager, dates, unités, payloads, erreurs, correction et rapprochement vérifiés.');
} finally { await server.close(); }
